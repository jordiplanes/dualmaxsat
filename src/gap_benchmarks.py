"""Gap-recovery experiment for abstract cores (Part 2, "Closing the Gap").

Generalizes the K3 counterexample to odd cycles C_n (n odd): soft unit
clauses are the vertices, hard binary conflict clauses the edges, so the
minimal cores are exactly the edges and the hitting-set problem is vertex
cover on an odd cycle, with known values

    z*_LP = n/2  (half-integral optimum, unit weights)
    z*    = (n+1)/2.

The experiment measures how much of the integrality gap z* - z*_LP the
rank-k rows generated by abstract cores recover in the *LP relaxation* of
the terminal master, comparing:

  - Baseline IHS-IP           (ordinary cores only)
  - + Threshold sweep         (price-guided separation, ordinary cores)
  - + Abstract (global)       (one abstraction set covering the cycle)
  - + Abstract (split)        (two contiguous arcs: coarser clustering)

A second experiment runs random vertex cover, unit-weight (auto
abstraction yields one aligned global set) versus weights drawn from
{1,2,3} (auto abstraction yields three clusters that cut across the
conflict structure), to measure the effect of aggregation alignment.

Outputs per-instance tables and gap_plot.png (used by the memo).
"""

import random
import time

import matplotlib.pyplot as plt
import pulp
from pysat.formula import WCNF

from ihs import IHSConfig, IHSSolver


def odd_cycle_wcnf(n: int, weights=None) -> WCNF:
    """C_n: soft units x_1..x_n, hard (¬x_i ∨ ¬x_{i+1}) around the cycle."""
    assert n % 2 == 1 and n >= 3
    weights = weights or [1] * n
    wcnf = WCNF()
    for i in range(n):
        wcnf.append([i + 1], weight=weights[i])
    for i in range(n):
        wcnf.append([-(i + 1), -((i + 1) % n + 1)])
    return wcnf


def exact_values(n: int, weights=None):
    """Exact z* and z*_LP of vertex cover on C_n via the full edge-row model."""
    weights = weights or [1] * n
    vals = {}
    for cat in ("Binary", "Continuous"):
        prob = pulp.LpProblem("vc", pulp.LpMinimize)
        if cat == "Binary":
            y = [pulp.LpVariable(f"y{i}", cat="Binary") for i in range(n)]
        else:
            y = [pulp.LpVariable(f"y{i}", lowBound=0, upBound=1) for i in range(n)]
        prob += pulp.lpSum(weights[i] * y[i] for i in range(n))
        for i in range(n):
            prob += y[i] + y[(i + 1) % n] >= 1
        prob.solve(pulp.PULP_CBC_CMD(msg=0))
        vals[cat] = pulp.value(prob.objective)
    return vals["Binary"], vals["Continuous"]


def split_sets(n: int):
    """Two contiguous arcs covering the cycle (both of size >= 3)."""
    half = (n + 1) // 2
    return [list(range(half)), list(range(half, n))]


def run(wcnf: WCNF, config: IHSConfig):
    solver = IHSSolver(wcnf, config)
    t0 = time.time()
    try:
        cost, _ = solver.solve()
    finally:
        solver.close()
    return cost, solver.stats, time.time() - t0


def vertex_cover_wcnf(n: int, p: float, seed: int, weighted: bool):
    """Random G(n,p) vertex cover as MaxSAT; weights 1 or drawn from {1,2,3}."""
    rng = random.Random(seed)
    edges = [(i, j) for i in range(n) for j in range(i + 1, n) if rng.random() < p]
    weights = [rng.choice([1, 2, 3]) if weighted else 1 for _ in range(n)]
    wcnf = WCNF()
    for i in range(n):
        wcnf.append([-(i + 1)], weight=weights[i])  # soft: vertex not in cover
    for i, j in edges:
        wcnf.append([i + 1, j + 1])                 # hard: edge covered
    return wcnf, edges, weights


def exact_vc(n, edges, weights):
    out = {}
    for cat in ("Binary", "Continuous"):
        prob = pulp.LpProblem("vc", pulp.LpMinimize)
        if cat == "Binary":
            y = [pulp.LpVariable(f"y{i}", cat="Binary") for i in range(n)]
        else:
            y = [pulp.LpVariable(f"y{i}", lowBound=0, upBound=1) for i in range(n)]
        prob += pulp.lpSum(weights[i] * y[i] for i in range(n))
        for i, j in edges:
            prob += y[i] + y[j] >= 1
        prob.solve(pulp.PULP_CBC_CMD(msg=0))
        out[cat] = pulp.value(prob.objective)
    return out["Binary"], out["Continuous"]


def vc_experiment():
    """Aligned vs misaligned aggregation on random vertex cover."""
    print("\n=== Random vertex cover: aggregation alignment ===")
    print(f"{'family':<10} {'n':>3} {'config':<9} "
          f"{'z*':>5} {'z*_LP':>6} {'termLP':>7} {'rec%':>6} {'it':>5} {'sat':>5} {'time':>6}")
    seeds = (42, 7, 99)
    for weighted, family in ((False, "unit"), (True, "weighted")):
        for n in (25, 35):
            agg = {"Baseline": [], "Sweep": [], "Abstract": []}
            for seed in seeds:
                wcnf, edges, weights = vertex_cover_wcnf(n, 0.2, seed, weighted)
                zstar, zlp = exact_vc(n, edges, weights)
                for label, cfg in (
                    ("Baseline", IHSConfig()),
                    ("Sweep", IHSConfig(threshold_sweep=True)),
                    ("Abstract", IHSConfig(auto_abstraction=True)),
                ):
                    cost, stats, dt = run(wcnf, cfg)
                    assert abs(cost - zstar) < 1e-6
                    rec = (100 * (stats.lp_value - zlp) / (zstar - zlp)
                           if zstar > zlp else 100.0)
                    agg[label].append((rec, stats.iterations, stats.sat_calls, dt))
            for label, rows in agg.items():
                rec = sum(r[0] for r in rows) / len(rows)
                it = sum(r[1] for r in rows) / len(rows)
                sat = sum(r[2] for r in rows) / len(rows)
                dt = sum(r[3] for r in rows) / len(rows)
                print(f"{family:<10} {n:>3} {label:<9} "
                      f"{'':>5} {'':>6} {'':>7} {rec:>5.0f}% {it:>5.1f} {sat:>5.1f} {dt:>5.1f}s")


def main():
    sizes = [3, 5, 7, 9, 11, 13, 15]

    configs = {
        "Baseline": lambda n: IHSConfig(),
        "+ Sweep": lambda n: IHSConfig(threshold_sweep=True),
        "+ Abstract (global)": lambda n: IHSConfig(auto_abstraction=True),
        "+ Abstract (split)": lambda n: (
            IHSConfig(abstraction_sets=split_sets(n)) if n >= 7 else None
        ),
    }

    lp_data = {label: [] for label in configs}
    gap_data = {label: [] for label in configs}
    iter_data = {label: [] for label in configs}
    zstars, zlps = [], []

    print(f"{'n':>3} {'z*':>5} {'z*_LP':>6}  "
          f"{'config':<20} {'cost':>5} {'termLP':>7} {'gap%':>6} {'it':>4} {'sat':>4} {'absR':>4}")
    for n in sizes:
        zstar, zlp = exact_values(n)
        zstars.append(zstar)
        zlps.append(zlp)
        for label, mk in configs.items():
            cfg = mk(n)
            if cfg is None:
                lp_data[label].append(None)
                gap_data[label].append(None)
                iter_data[label].append(None)
                continue
            cost, stats, _ = run(odd_cycle_wcnf(n), cfg)
            assert abs(cost - zstar) < 1e-6, f"wrong optimum on C_{n} ({label})"
            recovered = (stats.lp_value - zlp) / (zstar - zlp)
            lp_data[label].append(stats.lp_value)
            gap_data[label].append(100 * recovered)
            iter_data[label].append(stats.iterations)
            print(f"{n:>3} {zstar:>5.0f} {zlp:>6.2f}  "
                  f"{label:<20} {cost:>5.0f} {stats.lp_value:>7.2f} "
                  f"{100 * recovered:>5.0f}% {stats.iterations:>4} "
                  f"{stats.sat_calls:>4} {stats.abstract_rows:>4}")
        print()

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5.5))

    styles = {
        "Baseline": dict(marker="o", linestyle="--", color="tab:gray"),
        "+ Sweep": dict(marker="^", linestyle="--", color="tab:orange"),
        "+ Abstract (global)": dict(marker="s", linestyle="-", color="tab:blue"),
        "+ Abstract (split)": dict(marker="D", linestyle="-", color="tab:green"),
    }

    ax1.plot(sizes, zstars, color="black", linestyle="-", linewidth=1,
             label=r"$z^\star$ (IP optimum)")
    ax1.plot(sizes, zlps, color="black", linestyle=":", linewidth=1,
             label=r"$z^\star_{LP}$ (full LP)")
    for label in configs:
        pts = [(x, v) for x, v in zip(sizes, lp_data[label]) if v is not None]
        ax1.plot([p[0] for p in pts], [p[1] for p in pts], label=label,
                 **styles[label])
    ax1.set_xlabel("cycle length $n$ (odd)")
    ax1.set_ylabel("terminal master LP value")
    ax1.set_title("LP relaxation value of the terminal master on $C_n$")
    ax1.legend()
    ax1.grid(True)

    for label in configs:
        pts = [(x, v) for x, v in zip(sizes, gap_data[label]) if v is not None]
        ax2.plot([p[0] for p in pts], [p[1] for p in pts], label=label,
                 **styles[label])
    ax2.axhline(100, color="black", linewidth=1, linestyle="-")
    ax2.axhline(0, color="black", linewidth=1, linestyle=":")
    ax2.set_xlabel("cycle length $n$ (odd)")
    ax2.set_ylabel("integrality gap recovered (%)")
    ax2.set_title(r"Share of $z^\star - z^\star_{LP}$ recovered by the LP master")
    ax2.set_ylim(-120, 115)
    ax2.legend()
    ax2.grid(True)

    plt.tight_layout()
    out = "/Users/jordiplanes/repos/dualmaxsat/gap_plot.png"
    plt.savefig(out, dpi=150)
    print(f"Saved plot to {out}")

    vc_experiment()


if __name__ == "__main__":
    main()
